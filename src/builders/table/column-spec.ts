import { z } from 'zod';
import {
  identifierSchema,
  optionSchema,
  optionsSourceSchema,
} from '../shared/schema-primitives';

/**
 * Spec schema for the table builder. A `TableSpec` is the **projection** of an
 * entity model into DataGrid columns; the builder turns it into a
 * `use<Entity>Columns()` hook on top of the `data-grid-columns` column-factory.
 *
 * Validated with zod so an invalid spec fails loudly before any TSX is emitted.
 */

/** Dot-path accessor, e.g. `fullName` or `profile.name`. */
const FIELD_PATH = /^[a-zA-Z_$][\w$]*(\.[a-zA-Z_$][\w$]*)*$/;

const columnId = identifierSchema;

/** Semantic widths for repeatable dense admin-table column layouts. */
export const TABLE_COLUMN_SIZE_PRESET_NAMES = [
  'compact',
  'date',
  'number',
  'badge',
  'short',
  'medium',
  'tags',
  'long',
  'identity',
  'extraLong',
] as const;

export type TableColumnSizePreset =
  (typeof TABLE_COLUMN_SIZE_PRESET_NAMES)[number];

export const TABLE_COLUMN_SIZE_PRESETS: Record<TableColumnSizePreset, number> =
  {
    compact: 160,
    date: 150,
    number: 150,
    badge: 170,
    short: 180,
    medium: 220,
    tags: 240,
    long: 280,
    identity: 320,
    extraLong: 360,
  };

const sizePresetSchema = z.enum(TABLE_COLUMN_SIZE_PRESET_NAMES);

const fieldPath = z
  .string()
  .regex(
    FIELD_PATH,
    'field phải là đường dẫn thuộc tính hợp lệ (vd: profile.name)',
  );

/** Common meta forwarded into `ColumnDef.meta` by every column-factory builder. */
const commonMeta = {
  /** Optional react-intl message ID used instead of the literal header. */
  headerMessageId: z.string().min(1).optional(),
  headerClassName: z.string().optional(),
  cellClassName: z.string().optional(),
  size: z.number().int().positive().optional(),
  sizePreset: sizePresetSchema.optional(),
  pin: z.enum(['left', 'right']).optional(),
  visibility: z.boolean().optional(),
  enableSorting: z.boolean().optional(),
};

/** Accessor columns (text/number/date/…) all carry an id, header and a field. */
const accessorBase = {
  id: columnId,
  header: z.string().min(1),
  field: fieldPath,
  ...commonMeta,
};

const textColumn = z.object({
  kind: z.literal('text'),
  tooltipOnTruncate: z.boolean().optional(),
  ...accessorBase,
});

const numberColumn = z.object({
  kind: z.literal('number'),
  minimumFractionDigits: z.number().int().min(0).max(20).optional(),
  maximumFractionDigits: z.number().int().min(0).max(20).optional(),
  ...accessorBase,
});

const currencyColumn = z.object({
  kind: z.literal('currency'),
  ...accessorBase,
});

const percentColumn = z.object({
  kind: z.literal('percent'),
  fractionDigits: z.number().int().min(0).max(20).optional(),
  ...accessorBase,
});

const dateColumn = z.object({
  kind: z.literal('date'),
  mode: z.enum(['date', 'datetime', 'relative']).optional(),
  ...accessorBase,
});

/** One status entry in a badge column's config; all fields are serializable. */
const badgeStatus = z.object({
  label: z.string().min(1),
  variant: z.string().optional(),
  className: z.string().optional(),
  dotClassName: z.string().optional(),
});

const badgeColumn = z.object({
  kind: z.literal('badge'),
  config: z.record(z.string(), badgeStatus),
  badgeSize: z.enum(['sm', 'md', 'lg']).optional(),
  ...accessorBase,
});

const editableSelectColumn = z.object({
  kind: z.literal('editableSelect'),
  options: z.array(optionSchema).optional(),
  optionsFrom: optionsSourceSchema.optional(),
  placeholder: z.string().optional(),
  ...accessorBase,
});

const indexColumn = z.object({
  kind: z.literal('index'),
  id: columnId.optional(),
  header: z.string().min(1).optional(),
  ...commonMeta,
});

const selectColumn = z.object({
  kind: z.literal('select'),
});

/** Standard semantic row actions generated by the table builder. */
const actionPreset = z.enum([
  'primary',
  'view',
  'edit',
  'delete',
  'archive',
  'copy',
  'other',
]);

/** Configuration for tables that render parent group rows followed by children. */
const groupingSpec = z.object({
  /** Field on a child row that points to its parent group id. */
  parentIdField: fieldPath,
  /** Boolean field used to identify a synthetic group row. */
  isGroupField: fieldPath.default('isGroup'),
  /** Boolean field used by group-row renderers to expose expand state. */
  expandedField: fieldPath.default('isExpanded'),
});

/**
 * `actions`/`custom` cells are JSX/handlers the builder cannot serialize. The
 * generated hook exposes a `render<Id>` callback the owned container supplies.
 */
const actionsColumn = z.object({
  kind: z.literal('actions'),
  id: columnId.optional(),
  // An actions column can intentionally omit its label when the icon buttons
  // are self-explanatory and the table does not need a header caption.
  header: z.string().optional(),
  /** Optional standard actions; when present the builder emits callbacks and colored action buttons. */
  actionPresets: z.array(actionPreset).optional(),
  /** Derive the column width from the number of icon-only actions. */
  actionCount: z.number().int().min(1).optional(),
  ...commonMeta,
});

const customColumn = z.object({
  kind: z.literal('custom'),
  id: columnId,
  header: z.string().min(1),
  ...commonMeta,
});

export const columnSpecSchema = z.discriminatedUnion('kind', [
  textColumn,
  numberColumn,
  currencyColumn,
  percentColumn,
  dateColumn,
  badgeColumn,
  editableSelectColumn,
  indexColumn,
  selectColumn,
  actionsColumn,
  customColumn,
]);

export const tableSpecSchema = z
  .object({
    /** Row type name, e.g. `Employee`. */
    entity: identifierSchema,
    /** Import specifier for the row type, e.g. `../model/employee`. */
    modelImport: z.string().min(1),
    /** Hook name; defaults to `use<Entity>Columns`. */
    hookName: identifierSchema.optional(),
    /** Spec path recorded in the provenance banner of the generated file. */
    specPath: z.string().optional(),
    /** Optional reusable group-row/children-row helpers. */
    grouping: groupingSpec.optional(),
    columns: z.array(columnSpecSchema).min(1, 'cần ít nhất một cột'),
  })
  .superRefine((spec, ctx) => {
    spec.columns.forEach((column, index) => {
      if (column.size !== undefined && column.sizePreset !== undefined) {
        ctx.addIssue({
          code: 'custom',
          message: 'Chỉ khai báo size hoặc sizePreset, không dùng đồng thời',
          path: ['columns', index, 'sizePreset'],
        });
      }

      if (
        column.kind === 'editableSelect' &&
        column.optionsFrom !== 'prop' &&
        (!column.options || column.options.length < 1)
      ) {
        ctx.addIssue({
          code: 'custom',
          message:
            'Cột editableSelect dùng options tĩnh cần khai báo ít nhất một lựa chọn',
          path: ['columns', index, 'options'],
        });
      }

      if (
        column.kind === 'actions' &&
        column.actionCount !== undefined &&
        (column.size !== undefined || column.sizePreset !== undefined)
      ) {
        ctx.addIssue({
          code: 'custom',
          message:
            'actionCount đã tự tính size, không khai báo size hoặc sizePreset cùng lúc',
          path: ['columns', index, 'sizePreset'],
        });
      }
    });
  });

export type ColumnSpec = z.infer<typeof columnSpecSchema>;
export type TableSpec = z.infer<typeof tableSpecSchema>;
export type ColumnKind = ColumnSpec['kind'];
